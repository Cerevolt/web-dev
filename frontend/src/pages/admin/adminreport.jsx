
import React, { useState } from "react";
import Sidebar from "../../components/Sidebar";
import "./adminreport.css";

const reports = [
  { id: "RPT001", name: "Child Progress Report", category: "Progress", generatedBy: "Dr. Sharma", date: "28 Oct 2026", status: "Completed" },
  { id: "RPT002", name: "Assessment Summary", category: "Assessment", generatedBy: "Ms. Roy", date: "27 Oct 2026", status: "Completed" },
  { id: "RPT003", name: "Platform Usage Report", category: "Usage", generatedBy: "Administrator", date: "26 Oct 2026", status: "Pending" },
  { id: "RPT004", name: "Student Performance Report", category: "Performance", generatedBy: "Mr. Das", date: "25 Oct 2026", status: "Completed" },
  { id: "RPT005", name: "Assessment Summary", category: "Assessment", generatedBy: "Dr. Sharma", date: "24 Oct 2026", status: "Pending" },
];

function AdminReport() {
  const [search, setSearch] = useState("");
  const [category, setCategory] = useState("All");

  const filteredReports = reports.filter((report) => {
    const matchesSearch =
      report.name.toLowerCase().includes(search.toLowerCase()) ||
      report.id.toLowerCase().includes(search.toLowerCase());

    const matchesCategory =
      category === "All" || report.category === category;

    return matchesSearch && matchesCategory;
  });

  return (
    <div className="admin-layout">
      <Sidebar />

      <main className="admin-main">
        <header className="admin-header">
          <div className="header-search">
            <input type="text" placeholder="Search anything..." />
          </div>
          <div className="header-actions">
            <div className="admin-profile">
              <div className="admin-avatar">A</div>
              <div className="admin-profile-info">
                <strong>Administrator</strong>
                <span>System Admin</span>
              </div>
            </div>
          </div>
        </header>

        <div className="page-container">
          <div className="admin-report-heading">
            <div>
              <h1>Manage Reports</h1>
              <p>View and monitor reports generated across the platform.</p>
            </div>
          </div>

          <section className="report-summary">
            <div className="report-summary-card">
              <span>Total Reports</span>
              <strong>{reports.length}</strong>
            </div>
            <div className="report-summary-card">
              <span>Completed</span>
              <strong>{reports.filter((r) => r.status === "Completed").length}</strong>
            </div>
            <div className="report-summary-card">
              <span>Pending</span>
              <strong>{reports.filter((r) => r.status === "Pending").length}</strong>
            </div>
          </section>

          <section className="report-table-panel">
            <div className="report-toolbar">
              <input
                type="search"
                placeholder="Search reports..."
                value={search}
                onChange={(e) => setSearch(e.target.value)}
              />

              <select
                value={category}
                onChange={(e) => setCategory(e.target.value)}
              >
                <option value="All">All Categories</option>
                <option value="Progress">Progress</option>
                <option value="Assessment">Assessment</option>
                <option value="Usage">Usage</option>
                <option value="Performance">Performance</option>
              </select>
            </div>

            <div className="report-table-wrapper">
              <table className="report-table">
                <thead>
                  <tr>
                    <th>Report ID</th>
                    <th>Report Name</th>
                    <th>Category</th>
                    <th>Generated By</th>
                    <th>Date</th>
                    <th>Status</th>
                  </tr>
                </thead>
                <tbody>
                  {filteredReports.length > 0 ? (
                    filteredReports.map((report) => (
                      <tr key={report.id}>
                        <td>{report.id}</td>
                        <td>{report.name}</td>
                        <td>{report.category}</td>
                        <td>{report.generatedBy}</td>
                        <td>{report.date}</td>
                        <td>
                          <span className={`report-status ${report.status.toLowerCase()}`}>
                            {report.status}
                          </span>
                        </td>
                      </tr>
                    ))
                  ) : (
                    <tr>
                      <td colSpan="6" className="report-empty">
                        No reports found.
                      </td>
                    </tr>
                  )}
                </tbody>
              </table>
            </div>
          </section>
        </div>
      </main>
    </div>
  );
}

export default AdminReport;
